/** Rantai menu dari akar sampai item ber-kunci `key` (untuk remah navigasi). */
export function jejakMenu(key: string): ItemMenu[] {
    for (const m of MENU) {
        if (m.key === key) {
            return [m];
        }
        for (const a of m.anak ?? []) {
            if (a.key === key) {
                return [m, a];
            }
        }
    }
    return [];
}

/** Cari item menu (termasuk anak) berdasarkan kunci. */
export function cariMenu(daftar: ItemMenu[], key: string): ItemMenu | null {
    for (const m of daftar) {
        if (m.key === key) {
            return m;
        }
        if (m.anak) {
            const ketemu = cariMenu(m.anak, key);
            if (ketemu) {
                return ketemu;
            }
        }
    }
    return null;
}
